export const dialogueCount=Object.values(dialogueGroups).reduce((n,g)=>n+g.lines.length,0);
export function createDialogueDirector({recent={},random=Math.random}={}){
 const history={};for(const [k,v] of Object.entries(recent)){if(dialogueGroups[k]&&Array.isArray(v))history[k]=v.filter(Number.isInteger).filter(i=>i>=0&&i<dialogueGroups[k].lines.length).slice(-Math.max(1,dialogueGroups[k].lines.length-1));}
 let touches=[],lastTease=-Infinity,lastManual=-Infinity,nextAuto=Infinity,lastLine='';
 function pick(group){const bank=dialogueGroups[group]||dialogueGroups.touch;const key=dialogueGroups[group]?group:'touch';const used=history[key]||[];let available=bank.lines.map((text,i)=>({text,i})).filter(x=>!used.includes(x.i)&&x.text!==lastLine);if(!available.length)available=bank.lines.map((text,i)=>({text,i})).filter(x=>x.text!==lastLine);if(!available.length)available=[{text:bank.lines[0],i:0}];const chosen=available[Math.min(available.length-1,Math.floor(random()*available.length))];history[key]=[...used,chosen.i].slice(-Math.max(1,bank.lines.length-1));lastLine=chosen.text;return {text:chosen.text,group:key};}
 function schedule(now){nextAuto=now+(8+random()*4)*60000;}
 return {pick,history,schedule,
  touch({now=Date.now(),active=false,bond=1}={}){lastManual=now;touches=touches.filter(t=>now-t<45000);touches.push(now);if(active&&touches.length>=4&&now-lastTease>=90000){lastTease=now;return pick('tease');}const r=random();return pick(bond>=3&&r<.15?'bond':r<.25?'sister':r<.40?'everyday':'touch');},
  ambient({now=Date.now(),active=false,visible=true,modalOpen=false,duration=0}={}){if(!active||!visible||modalOpen||now<nextAuto||now-lastManual<60000)return null;schedule(now);return pick(duration>=45*60000&&random()<.4?'long':random()<.18?'encourage':'quiet');}
 };
}
