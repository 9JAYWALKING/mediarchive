export function routinePool(student,ctx,growth){
 if(ctx.mealEvent)return mealPool(student,ctx.mealEvent);
 const bank=routineLines[student]||routineLines.haru;
 const special=ctx.phase==='lunch'&&ctx.pathologyAfter?'pathology':ctx.phase==='dinner'&&ctx.lateDinner?'lateDinner':ctx.phase==='evening'&&!ctx.mealsConfigured&&ctx.minute<1150?'firstEvening':ctx.phase==='morning'&&ctx.noClass?'dayOff':null;
 const lines=[...bank[special||ctx.phase]];
 if(ctx.phase==='morning'&&ctx.next){
  const title=ctx.next.title,time=ctx.next.time;
  lines.push({ritsu:`첫 수업은 ${time}, 「${title}」네. 시작 전에 궁금한 것만 표시해 두자.`,haru:`오늘 첫 수업은 ${time}, 「${title}」이네! 시작 전에 낯선 말만 살짝 보고 갈까?`,nagi:`첫 수업이 ${time}에 있네. 「${title}」… 제목부터 천천히 훑어볼까?`,shiori:`첫 수업은 ${time}, 「${title}」야. 지금은 미리 훑고 궁금한 곳만 표시해 둬.`,rei:`${time}에 「${title}」 수업이 있네. 먼저 훑어보고, 무엇을 확인할지 정해 보자.`}[student]||illustrationNextClass(student,time,title)||lines[0]);
 }
 if(student==='haru'&&['review','evening'].includes(ctx.phase)&&growth?.totalDuration>0&&growth.cycles<5){
  const done=new Set(growth.done||[]),candidate=[1,2,6].flatMap(lecture=>['Wiki','J','JBL'].map(track=>({lecture,track}))).find(x=>!done.has(`${x.lecture}:${x.track}`));
  if(candidate){const title=schedule.find(l=>l.id===candidate.lecture).title;lines.push(`우리 이어서 할 거면 「${title}」 ${candidate.track} 어때? 아직 마침 표시가 없네. 끝냈다면 기록도 챙겨 줘!`);}
 }
 return {key:special||ctx.phase,lines};
}
